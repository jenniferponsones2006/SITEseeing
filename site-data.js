/* =====================================================
   TOUR PACKAGES
===================================================== */

const tourPackages = window.SITESEEING_PACKAGES.map(pkg => ({ ...pkg }));

/* =====================================================
   PACKAGE IMAGES
   Each package has its own folder of photos:

       images/packages/<package id>/1.jpg, 2.jpg, 3.jpg ...
       e.g. images/packages/intramuros-solo/1.jpg

   The photoCount in packages.js is how many photos each folder holds.
   On the package card, hovering cycles through all of them.
   If you add or remove photos, update that package's number.
   The destination photo from touristSpots is used as a
   fallback if a file is missing.
===================================================== */



const packageImageSource = {
    "National Museum Complex": "National Museum of Fine Arts"
};

tourPackages.forEach(pkg => {

    const spotName =
        packageImageSource[pkg.destination] || pkg.destination;

    const spot =
        touristSpots.find(place => place.name === spotName);

    pkg.fallbackImage = spot ? spot.image : "";

    const total = pkg.photoCount || 0;

    pkg.images = [];

    for (let i = 1; i <= total; i++) {
        pkg.images.push(`images/packages/${pkg.id}/${i}.jpg`);
    }

    if (pkg.customImage) {
        pkg.images = [pkg.customImage];
    }

    pkg.image = pkg.images[0] || pkg.fallbackImage;

});

