function confirmPayment() {

    if (!pendingReservation) {
        return;
    }


    const bookingId =
        "SITE-" +
        Date.now()
            .toString()
            .slice(-8);


    const booking = {

        ...pendingReservation,

        bookingId:

            bookingId,

        status:
            "Confirmed",

        paymentStatus:

            pendingReservation.paymentMethod === "Cash"

                ? "Pay at Venue"

                : "Payment Confirmed",

        createdAt:
            new Date().toISOString()

    };


    const bookings =
        JSON.parse(
            localStorage.getItem(
                "siteseeingBookings"
            ) || "[]"
        );


    bookings.push(booking);


    localStorage.setItem(
        "siteseeingBookings",
        JSON.stringify(bookings)
    );


    localStorage.setItem(
        "lastBooking",
        JSON.stringify(booking)
    );


    closeModal(
        "paymentModal"
    );


    showReservationSuccess(
        booking
    );


    pendingReservation = null;

}


