function setupHero() {

    const dots =
        document.getElementById("heroDots");

    dots.innerHTML = "";

    heroImages.forEach((image, index) => {

        const dot =
            document.createElement("button");

        dot.className =
            "hero-dot";

        if (index === 0) {
            dot.classList.add("active");
        }

        dot.onclick = () => {
            currentHero = index;
            changeHero();
        };

        dots.appendChild(dot);

    });

    changeHero();

}


function changeHero() {

    const hero =
        document.querySelector(".hero");

    hero.style.backgroundImage =
        `
        linear-gradient(
            rgba(0,0,0,0.38),
            rgba(0,0,0,0.45)
        ),
        url("${heroImages[currentHero]}")
        `;


    document
        .querySelectorAll(".hero-dot")
        .forEach((dot, index) => {

            dot.classList.toggle(
                "active",
                index === currentHero
            );

        });

}


setInterval(() => {

    currentHero =
        (currentHero + 1) % heroImages.length;

    changeHero();

}, 4500);


/* =====================================================
   PLACES
===================================================== */

function renderPlaces() {

    const grid =
        document.getElementById("placesGrid");

    const search =
        document
            .getElementById("placeSearch")
            .value
            .toLowerCase();

    const type =
        document.getElementById("typeFilter").value;

    const price =
        document.getElementById("priceFilter").value;


    const filtered =
        touristSpots.filter(spot => {

            const matchesSearch =
                spot.name
                    .toLowerCase()
                    .includes(search) ||
                spot.location
                    .toLowerCase()
                    .includes(search);


            const matchesType =
                type === "all" ||
                spot.categories.includes(type);


            const matchesPrice =
                price === "all" ||
                spot.priceType === price;


            return (
                matchesSearch &&
                matchesType &&
                matchesPrice
            );

        });


    if (filtered.length === 0) {

        grid.innerHTML = `
            <div class="empty-message">
                No places found.
            </div>
        `;

        return;
    }


    grid.innerHTML =
        filtered.map(spot => `

            <article class="place-card">

                <div class="place-image">

                    <img
                        src="${spot.image}"
                        alt="${spot.name}">

                </div>


                <div class="place-info">

                    <h3>
                        ${spot.name}
                    </h3>

                  <p class="detail-location">
     ${spot.location}
</p>

<a
    href="${spot.map}"
    target="_blank"
    rel="noopener noreferrer"
    class="map-btn">

     View Location on Google Maps

</a>

                    <div class="place-meta">

                        <span>
                            ${spot.categories[0]}
                        </span>

                        <span>
                            ${
                                spot.priceType === "free"
                                ? "Free"
                                : "Paid"
                            }
                        </span>

                    </div>


                    <button
                        class="view-btn"
                        onclick="openPlaceDetails(${spot.id})">

                        View Details

                    </button>

                </div>

            </article>

        `).join("");

}


